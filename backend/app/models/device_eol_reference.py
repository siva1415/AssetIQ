from datetime import date, datetime
from sqlalchemy import BigInteger, Column, Date, DateTime, Identity, Integer, String
from app.db.base import Base


class DeviceEolReference(Base):
    """
    SQLAlchemy model mapping the existing `device_eol_reference` table.
    Identity column generated by PostgreSQL.
    """
    __tablename__ = "device_eol_reference"

    eol_id = Column(
        BigInteger().with_variant(Integer, "sqlite"),
        Identity(always=False),
        primary_key=True,
        autoincrement=True,
    )
    manufacturer = Column(String(100), nullable=True, index=True)
    model = Column(String(150), nullable=True, index=True)
    eol_date = Column(Date, nullable=True, index=True)
    reference_source = Column(String(255), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=True)
    updated_at = Column(DateTime(timezone=True), nullable=True)

    def __repr__(self) -> str:
        return f"<DeviceEolReference(id={self.eol_id}, manufacturer='{self.manufacturer}', model='{self.model}', eol_date={self.eol_date})>"
