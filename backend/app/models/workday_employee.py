from datetime import date, datetime
from sqlalchemy import BigInteger, Column, Date, DateTime, Identity, String
from app.db.base import Base


class WorkdayEmployee(Base):
    """
    SQLAlchemy model mapping the existing `workday_employees` table.
    Identity column generated by PostgreSQL.
    """
    __tablename__ = "workday_employees"

    employee_id = Column(BigInteger, Identity(always=False), primary_key=True, autoincrement=True)
    user_id = Column(String(100), unique=True, nullable=False, index=True)
    full_name = Column(String(200), nullable=False, index=True)
    email_work = Column(String(255), nullable=True)
    email_home = Column(String(255), nullable=True)
    department = Column(String(150), nullable=True, index=True)
    division = Column(String(150), nullable=True, index=True)
    job_title = Column(String(150), nullable=True)
    employee_status = Column(String(30), nullable=True, default="Active", index=True)
    manager_user_name = Column(String(50), nullable=True)
    manager_name = Column(String(200), nullable=True)
    manager_level_1_user_name = Column(String(100), nullable=True)
    manager_level_2_user_name = Column(String(100), nullable=True)
    manager_level_3_user_name = Column(String(100), nullable=True)
    manager_level_4_user_name = Column(String(100), nullable=True)
    manager_level_5_user_name = Column(String(100), nullable=True)
    manager_level_6_user_name = Column(String(100), nullable=True)
    manager_level_7_user_name = Column(String(100), nullable=True)
    manager_level_8_user_name = Column(String(100), nullable=True)
    manager_level_9_user_name = Column(String(100), nullable=True)
    location = Column(String(150), nullable=True)
    hire_date = Column(Date, nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=True)
    updated_at = Column(DateTime(timezone=True), nullable=True)
    last_synced_at = Column(DateTime(timezone=True), nullable=True)

    def __repr__(self) -> str:
        return f"<WorkdayEmployee(id={self.employee_id}, user_id='{self.user_id}', full_name='{self.full_name}')>"
